"""Quest chronicle data: quests/text/*.json (hints and full solutions, English + French) -> one Lua file per language.

    python build_q_lua.py      -> quests/data/english.lua, quests/data/french.lua

PSXQ_DATA[title strref] = { g = game, k = kind, c = chapter, w = place, h = { hints }, s = full solution }.
french.lua also sets PSXQ_Strings (the page's French UI). The install copies its language's file (English when there
is none) to override/M_PSXQD.lua. Keys are EET 2.7.3 title strrefs (quests/index.json).
"""
import glob
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
OUT = os.path.join(HERE, 'data')

FR_UI = {
    'q_title': 'Quêtes', 'q_all': 'Toutes les quêtes', 'q_bg1': "Baldur's Gate", 'q_sod': 'Siege of Dragonspear',
    'q_bg2': "Shadows of Amn", 'q_tob': 'Throne of Bhaal', 'q_main': 'Histoire principale', 'q_companion': 'Compagnons',
    'q_side': 'Quêtes secondaires', 'q_search': 'Rechercher', 'q_active': 'En cours', 'q_done': 'Terminées',
    'q_none': 'Jamais vues', 'q_status_active': 'En cours', 'q_status_done': 'Terminée',
    'q_status_none': 'Pas commencée', 'q_journal': 'Journal', 'q_hints': 'Indices', 'q_solution': 'Solution complète',
    'q_close': 'Fermer', 'q_count': '%d quêtes : %d terminées, %d en cours',
    'q_select': 'Choisissez une quête dans la liste.',
    'q_not_started': "Vous n'avez pas encore commencé cette quête.\n\nLes indices et la solution complète sont derrière "
                     "les boutons à droite.",
    'q_no_hints': "Pas encore d'indices pour cette quête.", 'q_no_solution': 'Pas encore de solution pour cette quête.',
    'q_chapter': 'Chapitre %s', 'q_any': "N'importe quand", 'q_completed': 'Quête terminée.',
    'q_spoiler': 'Attention, révélations !', 'q_skin': 'Tableau : %s', 'q_skin_1': 'notes épinglées',
    'q_skin_2': 'peint', 'q_none_found': 'Aucune quête ne correspond.', 'q_mods': 'Mods',
    'q_mod_quest': "Quête ajoutée par le mod %s.\nPas d'indices ni de solution pour les quêtes des mods.",
}


def lua_str(s):
    s = str(s).replace('\r', '')
    n = 0
    while (']' + '=' * n + ']') in s:
        n += 1
    return '[' + '=' * n + '[' + s + ']' + '=' * n + ']'


def load():
    quests = {}
    for path in sorted(glob.glob(os.path.join(HERE, 'text', 'batch_*.json'))):
        if '.part' in path:
            continue
        for q in json.load(open(path, encoding='utf-8')):
            quests[int(q['title'])] = q
    return quests


def write(lang, quests):
    sfx = 'en' if lang == 'english' else 'fr'
    out = ['-- Quest chronicle data (%s). GENERATED by quests/build_q_lua.py from quests/text/*.json: edit those.' % lang,
           '-- Installed as override/M_PSXQD.lua; read by M_PSXQ.lua.', 'PSXQ_DATA = {']
    for strref in sorted(quests):
        q = quests[strref]
        hints = q.get('hints_' + sfx) or q.get('hints_en') or []
        sol = q.get('solution_' + sfx) or q.get('solution_en') or ''
        where = q.get('where_' + sfx) or q.get('where_en') or ''
        out.append('[%d] = { g = %s, k = %s, c = %s, w = %s, h = { %s }, s = %s },' % (
            strref, lua_str(q.get('game', '')), lua_str(q.get('kind', 'side')), lua_str(q.get('chapter', '')),
            lua_str(where), ', '.join(lua_str(h) for h in hints), lua_str(sol)))
    out.append('}')
    if lang == 'french':
        out.append('PSXQ_Strings = {')
        out += ['\t%s = %s,' % (k, lua_str(v)) for k, v in FR_UI.items()]
        out.append('}')
    os.makedirs(OUT, exist_ok=True)
    path = os.path.join(OUT, lang + '.lua')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(out) + '\n')
    print('written', path, len(quests), 'quests', os.path.getsize(path), 'bytes')


def main():
    quests = load()
    for lang in ('english', 'french'):
        write(lang, quests)


if __name__ == '__main__':
    main()
